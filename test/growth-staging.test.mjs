import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { stagingConfig } from '../scripts/prepare-growth-staging.mjs';
const production=JSON.parse(await readFile(new URL('../wrangler.jsonc',import.meta.url),'utf8'));
test('staging preparation rejects production database IDs and production hostnames',()=>{assert.throws(()=>stagingConfig(production,{databaseId:production.d1_databases[0].database_id,hostname:'staging.auradigitalworks.com'},'/repo'));assert.throws(()=>stagingConfig(production,{databaseId:'aaaaaaaa-bbbb-cccc-dddd-eeeeeeeeeeee',hostname:'auradigitalworks.com'},'/repo'));assert.throws(()=>stagingConfig(production,{databaseId:'aaaaaaaa-bbbb-cccc-dddd-eeeeeeeeeeee',hostname:'staging.attacker.test'},'/repo'));});
test('staging isolates storage and lets fixture users test private drafts without providers',()=>{
 const databaseId='aaaaaaaa-bbbb-cccc-dddd-eeeeeeeeeeee',hostname='growth-staging.auradigitalworks.com';
 const config=stagingConfig(production,{databaseId,hostname},'/repo');
 assert.deepEqual(config.routes,[{pattern:hostname,custom_domain:true},{pattern:'staging.auramenu.space/api/auramenu/*',zone_name:'auramenu.space'}]);
 assert.deepEqual(config.d1_databases,[{binding:'DB',database_id:databaseId,database_name:'auradigital-staging-db',migrations_dir:'/repo/migrations'}]);
 assert.equal(config.vars.CUSTOMER_AUTH_ORIGIN,'https://'+hostname);
 assert.equal(config.vars.AURAMENU_ORIGIN,'https://staging.auramenu.space');
 assert.equal(config.vars.MENU_DRAFTS_ENABLED,'true');
 assert.equal(config.vars.CUSTOMER_EMAIL_ENABLED,'false');
 assert.equal(config.vars.GOOGLE_LOGIN_ENABLED,'false');
 assert.equal(config.vars.AI_PROVIDER,'disabled');
 assert.equal(config.keep_vars,false);
 for(const field of ['triggers','ai','send_email','secrets'])assert.equal(config[field],undefined,field);
 assert.notEqual(config.ratelimits[0].namespace_id,production.ratelimits[0].namespace_id);
 assert.equal(config.assets.directory,'/repo');
 assert.equal(config.build.cwd,'/repo');
});
