"""Create transparent site assets from the same 3D rig used in the studio."""
import json
from pathlib import Path
import sys

from PIL import Image

source = Path(sys.argv[1])
output = Path('media/auri/studio-v1')
output.mkdir(parents=True, exist_ok=True)
bounds = {}
for name in ('body', 'head', 'armL', 'armR', 'legL', 'legR', 'full', 'avatar'):
    image = Image.open(source / f'{name}.png').convert('RGBA')
    box = image.getchannel('A').getbbox()
    if box is None:
        raise ValueError(f'{name} did not render')
    left, top, right, bottom = box
    cropped = image.crop(box)
    if name in ('full', 'avatar'):
        cropped.thumbnail((390, 460), Image.Resampling.LANCZOS)
    else:
        bounds[name] = [left / 2, top / 2, (right - left) / 2, (bottom - top) / 2]
        cropped = cropped.resize((round(cropped.width * .67), round(cropped.height * .67)), Image.Resampling.LANCZOS)
    cropped.save(output / f'{name}.webp', 'WEBP', quality=89, method=6)

(output / 'layers.js').write_text(
    '// Generated by scripts/render-auri-parts.mjs. SVG coordinates of the transparent crops.\n'
    'export const AURI_LAYERS = ' + json.dumps(bounds, indent=2) + ';\n',
    encoding='utf-8',
)
